export interface RejectionLogItem {
  id: string;
  no?: number;
  nik_npwp?: string;
  no_permohonan?: string;
  nama: string;
  alamat?: string;
  tanggal_pengajuan?: string;
  plafon_pengajuan: number;
  jenis_kredit: string; // Modal Kerja, Investasi, Konsumtif/Multiguna, KPR, KTA/Modal Kerja
  peruntukan_kredit?: string; // Refinancing Kredit, Pembiayaan Project, Tambahan Modal Usaha, Pembelian 1 Unit Rumah, Take Over, dll.
  alasan_ditolak: string; // Detail alasan penolakan
  kapasitas: string; // TOLAK, DITERIMA, DIPERTIMBANGKAN, BATAL PENGAJUAN
  jaminan?: string; // SHM, SHM & BPKB, HGB, dll.
  informasi_negatif?: string; // Catatan negatif, masalah warga, info jaminan
  kantor?: string; // Kuta, KPO, dll.
  kepala_cabang?: string;
  analis?: string;
  tanggal_ditolak?: string;
  created_at?: string;
  updated_at?: string;
}

export interface RejectionStats {
  totalRejections: number;
  totalPlafon: number;
  byKapasitas: Record<string, number>;
  byJenisKredit: Record<string, number>;
  byKantor: Record<string, number>;
}

